import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createServer } from 'vite';
import { PDFDocument, PDFName, PDFHexString, PDFDict, PDFNumber } from 'pdf-lib';
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
try {
  const { defaultStyle, reviewCsv, reviewRows, reviewGeometry, validateReviewMark, markVisible } = await server.ssrLoadModule('/src/reviewModel.ts');
  const { exportDrawingPdf, importDrawingPdf, reviewReport } = await server.ssrLoadModule('/src/drawingPdf.ts');
  const { carryReview, inspectCarryPdf } = await server.ssrLoadModule('/src/carryReview.ts');
  const { snapPoint, alignRevision } = await server.ssrLoadModule('/src/drawingGeometry.ts');
  const { measurementLabel } = await server.ssrLoadModule('/src/measurements.ts');
  const source = await PDFDocument.create(); source.addPage([612, 792]); source.addPage([612, 792]);
  const bytes = await source.save();
  const mark = { id: 'cloud-note', page: 0, kind: 'Cloud callout', points: [[40, 450], [150, 500], [180, 530]], text: 'Coordinate with structural', style: defaultStyle, createdAt: 100 };
  const meta = { author: 'A reviewer', discipline: 'Structural', status: 'Answered', subject: 'Beam clearance', locked: false, group: 'g1', replies: [{ author: 'Designer', text: 'Revised on S101', at: 200 }] };
  const measurement = { id: 'length', page: 0, kind: 'Length', points: [[20, 20], [120, 20]], scale: { unit: 'ft', unitsPerPoint: .1 } };
  const data = { scales: { 0: measurement.scale }, review: [mark], reviewMeta: { [mark.id]: meta }, measurements: [measurement] };
  assert.equal(validateReviewMark(mark, 2), true);
  assert.equal(validateReviewMark({ ...mark, points: [[NaN, 0], [1, 1]] }, 2), false);
  assert.ok(reviewGeometry(mark).paths.length >= 3);
  const result = await exportDrawingPdf(bytes, data, [2, 1]);
  const exported = await PDFDocument.load(result);
  const annotations = exported.getPage(1).node.Annots();
  assert.equal(annotations.size(), 4);
  assert.equal(annotations.lookup(0).get(PDFName.of('Subtype')).toString(), '/FreeText');
  assert.ok(annotations.lookup(0).lookup(PDFName.of('AP')) instanceof PDFDict);
  assert.ok(annotations.lookup(3).lookup(PDFName.of('Measure')) instanceof PDFDict);
  const imported = await importDrawingPdf(result);
  assert.equal(imported.drawing.review[0].page, 1);
  assert.equal(imported.drawing.review[0].text, mark.text);
  assert.deepEqual(imported.drawing.reviewMeta[mark.id], meta);
  assert.equal(imported.drawing.measurements[0].page, 1);
  assert.deepEqual(imported.drawing.scales[1], measurement.scale);
  assert.equal((await PDFDocument.load(imported.bytes)).getPage(1).node.Annots().size(), 0, 'native appearances are removed before editable overlays are displayed');
  // External readers may move the annotation and change its note. Those edits win over the stored geometry.
  const annotation = annotations.lookup(0), rect = annotation.lookup(PDFName.of('Rect')).asArray().map(v => v.asNumber());
  annotation.set(PDFName.of('Contents'), PDFHexString.fromText('Changed in another reader'));
  annotation.set(PDFName.of('Rect'), exported.context.obj(rect.map((n, i) => n + (i % 2 ? 5 : 10))));
  annotation.set(PDFName.of('State'), PDFHexString.fromText('Completed'));
  exported.getPage(1).node.addAnnot(exported.context.register(exported.context.obj({ Type: 'Annot', Subtype: 'Text', Rect: [20, 20, 40, 40], IRT: annotations.get(0), RT: 'R', Contents: PDFHexString.fromText('External reviewer reply'), T: PDFHexString.fromText('External reviewer') })));
  exported.getPage(1).node.addAnnot(exported.context.register(exported.context.obj({ Type: 'Annot', Subtype: 'Text', Rect: [20, 20, 40, 40], IRT: annotations.get(annotations.size() - 1), RT: 'R', Contents: PDFHexString.fromText('Nested reviewer reply'), T: PDFHexString.fromText('Designer') })));
  const moved = await importDrawingPdf(await exported.save());
  assert.equal(moved.drawing.reviewMeta[mark.id].status, 'Resolved');
  assert.ok(moved.drawing.reviewMeta[mark.id].replies.some(r => r.text === 'External reviewer reply'));
  assert.ok(moved.drawing.reviewMeta[mark.id].replies.some(r => r.text === 'Nested reviewer reply'), 'nested replies are attached to their restored root');
  assert.equal((await PDFDocument.load(moved.bytes)).getPage(1).node.Annots().size(), 0, 'restored discussion leaves no orphan native replies');
  assert.equal(moved.drawing.review[0].text, 'Changed in another reader');
  assert.deepEqual(moved.drawing.review[0].points[0], [50, 455]);
  const again = await PDFDocument.load(await exportDrawingPdf(imported.bytes, imported.drawing));
  assert.equal(again.getPage(1).node.Annots().size(), 4, 'saving again does not duplicate marks');
  const flat = await PDFDocument.load(await exportDrawingPdf(bytes, data, null, true));
  assert.equal(flat.getPage(0).node.Annots().size(), 0);
  assert.ok(flat.getPage(0).node.Contents());
  assert.equal((await importDrawingPdf(await flat.save())).drawing, undefined);
  const malformed = await PDFDocument.load(result);
  malformed.getPage(1).node.Annots().lookup(0).set(PDFName.of('FolioReview'), PDFHexString.fromText('{broken'));
  const safe = await importDrawingPdf(await malformed.save());
  assert.equal((await PDFDocument.load(safe.bytes)).getPage(1).node.Annots().size(), 3, 'invalid records leave their visible annotations intact');
  const nativeDoc = await PDFDocument.load(bytes);
  const nativeRef = nativeDoc.context.register(nativeDoc.context.obj({ Type: 'Annot', Subtype: 'FreeText', Rect: [20, 20, 120, 50], Contents: PDFHexString.fromText('Existing note') }));
  nativeDoc.getPage(0).node.addAnnot(nativeRef);
  const nativeData = { scales: {}, measurements: [], reviewMeta: { 'existing-note': meta } };
  const nativeSaved = await exportDrawingPdf(await nativeDoc.save(), nativeData, null, false, undefined, [{ id: 'existing-note', page: 0, type: 'freetext', text: 'Existing note', data: { rect: [20, 20, 120, 50] } }]);
  const nativeImported = await importDrawingPdf(nativeSaved);
  assert.ok(Object.values(nativeImported.drawing.reviewMeta).some(m => m.subject === meta.subject && m.status === meta.status), 'review fields on existing Folio annotations survive exported copies');
  const hiddenNative = await exportDrawingPdf(await nativeDoc.save(), { ...nativeData, layers: [{ id: 'native-layer', name: 'Native notes', visible: false }], reviewMeta: { 'existing-note': { ...meta, layer: 'native-layer' } } }, null, false, undefined, [{ id: 'existing-note', page: 0, type: 'freetext', text: 'Existing note', data: { rect: [20, 20, 120, 50] } }]);
  const hiddenNativePdf = await PDFDocument.load(hiddenNative);
  assert.ok(hiddenNativePdf.getPage(0).node.Annots().lookup(0).lookup(PDFName.of('F')).asNumber() & 2, 'saved visibility is honored by readers that ignore layers');
  const nativeReopened = await importDrawingPdf(hiddenNative);
  assert.equal(nativeReopened.drawing.layers[0].visible, false);
  assert.equal((await PDFDocument.load(nativeReopened.bytes)).getPage(0).node.Annots().lookup(0).lookup(PDFName.of('F')).asNumber() & 2, 0, 'Folio can reveal a native annotation by switching its layer back on after reopening');
  const formDoc = await PDFDocument.load(bytes);
  const field = formDoc.getForm().createTextField('test'); field.setText('Filled form'); field.addToPage(formDoc.getPage(0), { x: 10, y: 100, width: 120, height: 20 });
  formDoc.getForm().updateFieldAppearances();
  const finalForm = await PDFDocument.load(await exportDrawingPdf(await formDoc.save(), { scales: {}, measurements: [] }, null, true));
  assert.equal(finalForm.getForm().getFields().length, 0, 'flattened copies do not retain editable form fields');
  const unicode = { ...data, review: [{ ...mark, text: 'Διάσταση — размер' }] };
  const font = new Uint8Array(readFileSync('node_modules/pdfjs-dist/standard_fonts/LiberationSans-Regular.ttf'));
  const international = await exportDrawingPdf(bytes, unicode, undefined, false, font);
  assert.equal((await importDrawingPdf(international)).drawing.review[0].text, unicode.review[0].text);
  const rows = reviewRows(data, [], measurementLabel);
  assert.equal(rows.length, 2); assert.match(reviewCsv(rows), /Answered/);
  assert.match(reviewCsv([{ ...rows[0], text: '=HYPERLINK("bad")' }]), /'=HYPERLINK/);
  assert.equal((await PDFDocument.load(await reviewReport(rows, 'Review report'))).getPageCount(), 1);
  assert.deepEqual(snapPoint([9.8, 10.2], [[10, 10]], 1).point, [10, 10]);
  assert.deepEqual(snapPoint([9.8, 10.2], [], 1).point, [9.8, 10.2]);
  const angle = snapPoint([10, 2], [], 1, [0, 0], true).point;
  assert.equal(angle[1], 0);
  assert.deepEqual(alignRevision([[10, 20], [10, 40]], [[0, 0], [10, 0]]), [0, 2, -2, 0, 10, 20]);
  assert.throws(() => alignRevision([[0, 0], [1, 1]], [[0, 0], [0, 0]]));
  // Standard layers retain hidden marks in editable copies and omit them from final copies.
  const layeredData = { ...data, layers: [{ id: 'structural', name: 'Structural review', visible: false }], reviewMeta: { ...data.reviewMeta, [mark.id]: { ...meta, layer: 'structural' }, [measurement.id]: { ...meta, layer: 'structural' } } };
  const layered = await exportDrawingPdf(bytes, layeredData);
  const layerPdf = await PDFDocument.load(layered);
  const layerGroups = layerPdf.catalog.lookup(PDFName.of('OCProperties')).lookup(PDFName.of('OCGs'));
  assert.equal(layerGroups.size(), 1);
  assert.equal(layerPdf.getPage(0).node.Annots().lookup(0).get(PDFName.of('OC')).toString(), layerGroups.get(0).toString());
  const layerImport = await importDrawingPdf(layered);
  assert.deepEqual(layerImport.drawing.layers, layeredData.layers);
  assert.equal(markVisible(layerImport.drawing, mark.id), false);
  assert.equal(layerImport.drawing.review.length, 1, 'hidden marks remain editable after reopening');
  const hiddenFinal = await PDFDocument.load(await exportDrawingPdf(bytes, layeredData, null, true));
  assert.equal(hiddenFinal.getPage(0).node.Annots().size(), 0);
  assert.equal((await importDrawingPdf(await hiddenFinal.save())).drawing, undefined, 'final copies do not reopen as editable layer data');
  assert.equal(hiddenFinal.getPage(0).node.Contents(), undefined, 'hidden mark appearances are not painted into final pages');
  assert.match(reviewCsv(reviewRows(layeredData, [], measurementLabel)), /Structural review/);
  // Other readers can change native endpoint arrays, stroke, opacity, weight, subject, and layer defaults.
  const nativeEdit = await PDFDocument.load(await exportDrawingPdf(bytes, { ...data, review: [{ ...mark, kind: 'Line', points: [[50, 60], [150, 60]] }] }));
  const editedLine = nativeEdit.getPage(0).node.Annots().lookup(0);
  editedLine.set(PDFName.of('L'), nativeEdit.context.obj([60, 80, 180, 90]));
  editedLine.set(PDFName.of('C'), nativeEdit.context.obj([0, 1, 0]));
  editedLine.set(PDFName.of('CA'), PDFNumber.of(.4));
  editedLine.set(PDFName.of('BS'), nativeEdit.context.obj({ W: 3, S: 'D', D: [1, 3] }));
  editedLine.set(PDFName.of('Subj'), PDFHexString.fromText('External subject'));
  const stateReply = nativeEdit.getPage(0).node.Annots().asArray().map(ref => nativeEdit.context.lookup(ref)).find(dict => dict.has(PDFName.of('FolioStatus')));
  stateReply.set(PDFName.of('State'), PDFHexString.fromText('Completed'));
  const nativeRoundtrip = await importDrawingPdf(await nativeEdit.save());
  assert.equal(nativeRoundtrip.drawing.reviewMeta[mark.id].status, 'Resolved', 'standard PDF review-state replies edited elsewhere are adopted');
  assert.deepEqual(nativeRoundtrip.drawing.review[0].points, [[60, 80], [180, 90]]);
  assert.equal(nativeRoundtrip.drawing.review[0].style.color, '#00ff00');
  assert.equal(nativeRoundtrip.drawing.review[0].style.width, 3);
  assert.equal(nativeRoundtrip.drawing.review[0].style.opacity, .4);
  assert.equal(nativeRoundtrip.drawing.review[0].style.dash, 'dotted');
  assert.equal(nativeRoundtrip.drawing.reviewMeta[mark.id].subject, 'External subject');
  const defaults = layerPdf.catalog.lookup(PDFName.of('OCProperties')).lookup(PDFName.of('D'));
  defaults.set(PDFName.of('OFF'), layerPdf.context.obj([])); defaults.set(PDFName.of('ON'), layerPdf.context.obj([layerGroups.get(0)]));
  assert.equal((await importDrawingPdf(await layerPdf.save())).drawing.layers[0].visible, true);
  // Transfer a mixed review, including a native annotation without a name and its discussion.
  const carrySource = await PDFDocument.load(layered);
  const sourcePage = carrySource.getPage(0);
  const nativeCarry = carrySource.context.register(carrySource.context.obj({ Type: 'Annot', Subtype: 'FreeText', Rect: [10, 10, 100, 30], T: PDFHexString.fromText('External author'), Contents: PDFHexString.fromText('External note'), P: sourcePage.ref }));
  sourcePage.node.addAnnot(nativeCarry);
  sourcePage.node.addAnnot(carrySource.context.register(carrySource.context.obj({ Type: 'Annot', Subtype: 'Text', Rect: [10, 10, 20, 20], IRT: nativeCarry, Contents: PDFHexString.fromText('Native reply') })));
  sourcePage.node.addAnnot(carrySource.context.register(carrySource.context.obj({ Type: 'Annot', Subtype: 'Popup', Rect: [10, 10, 20, 20], Parent: nativeCarry })));
  sourcePage.node.addAnnot(carrySource.context.register(carrySource.context.obj({ Type: 'Annot', Subtype: 'Link', Rect: [0, 0, 20, 20] })));
  const carryBytes = await carrySource.save();
  assert.equal((await inspectCarryPdf(carryBytes))[0].count, 3);
  const revision = await PDFDocument.load(bytes);
  revision.getPage(1).node.addAnnot(revision.context.register(revision.context.obj({ Type: 'Annot', Subtype: 'Text', Rect: [0, 0, 20, 20], NM: PDFHexString.fromText('already-on-revision'), Contents: PDFHexString.fromText('Existing revision comment') })));
  const revisedBytes = await revision.save();
  const carried = await carryReview(carryBytes, revisedBytes, [{ from: 0, to: 1 }], 'Original drawings.pdf');
  assert.equal(carried.carried, 3); assert.equal(carried.duplicates, 0);
  const carriedPdf = await PDFDocument.load(carried.bytes), carriedPage = carriedPdf.getPage(1);
  assert.equal(carriedPdf.context.enumerateIndirectObjects().filter(([, object]) => object instanceof PDFDict && object.get(PDFName.of('Type'))?.toString() === '/Page').length, 2, 'carrying annotations does not embed the old drawing pages');
  assert.equal(carriedPage.node.Annots().size(), 10, 'native replies and popups follow their parents; links do not');
  for (let i = 1; i < carriedPage.node.Annots().size(); i++) assert.equal(carriedPage.node.Annots().lookup(i).get(PDFName.of('P')).toString(), carriedPage.ref.toString());
  const carriedImport = await importDrawingPdf(carried.bytes);
  assert.equal(carriedImport.drawing.review[0].page, 1);
  assert.equal(carriedImport.drawing.measurements[0].page, 1);
  assert.equal(carriedImport.drawing.reviewMeta[mark.id].status, meta.status);
  assert.equal(carriedImport.drawing.reviewMeta[mark.id].carriedFrom.document, 'Original drawings.pdf');
  assert.equal(carriedImport.drawing.reviewMeta[mark.id].replies[0].text, meta.replies[0].text);
  assert.deepEqual(carriedImport.drawing.layers, layeredData.layers);
  assert.ok(Object.values(carriedImport.drawing.reviewMeta).some(m => m.author === 'External author' && m.carriedFrom));
  const repeatCarry = await carryReview(carryBytes, carried.bytes, [{ from: 0, to: 1 }], 'Original drawings.pdf');
  assert.equal(repeatCarry.carried, 0); assert.equal(repeatCarry.duplicates, 3);
  assert.equal((await PDFDocument.load(repeatCarry.bytes)).getPage(1).node.Annots().size(), 10);
  assert.equal((await PDFDocument.load(revisedBytes)).getPage(1).node.Annots().size(), 1, 'the supplied revised document stays untouched');
  await assert.rejects(carryReview(carryBytes, revisedBytes, [{ from: 0, to: 0 }, { from: 1, to: 0 }], 'old.pdf'), /only once/);
  revision.getPage(1).setCropBox(2, 0, 610, 792);
  await assert.rejects(carryReview(carryBytes, await revision.save(), [{ from: 0, to: 1 }], 'old.pdf'), /different size, crop/);
  console.log('PASS layer visibility and PDF groups, external native edits, carry-forward mapping, provenance, replies, duplicate prevention and geometry checks');
  console.log('PASS review PDF round trips, external edits, flattening, Unicode, report, CSV, snapping and revision alignment');
} finally { await server.close(); }
