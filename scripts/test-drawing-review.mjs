import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createServer } from 'vite';
import { PDFDocument, PDFName, PDFHexString, PDFDict } from 'pdf-lib';
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
try {
  const { defaultStyle, reviewCsv, reviewRows, reviewGeometry, validateReviewMark } = await server.ssrLoadModule('/src/reviewModel.ts');
  const { exportDrawingPdf, importDrawingPdf, reviewReport } = await server.ssrLoadModule('/src/drawingPdf.ts');
  const { snapPoint, alignRevision } = await server.ssrLoadModule('/src/drawingGeometry.ts');
  const { measurementLabel } = await server.ssrLoadModule('/src/measurements.ts');
  const source = await PDFDocument.create(); source.addPage([612, 792]); source.addPage([612, 792]);
  const bytes = await source.save();
  const mark = { id: 'cloud-note', page: 0, kind: 'Cloud callout', points: [[40, 450], [150, 500], [180, 530]], text: 'Coordinate with structural', style: defaultStyle, createdAt: 100 };
  const meta = { author: 'A reviewer', discipline: 'Structural', status: 'Answered', subject: 'Beam clearance', locked: false, group: 'g1', replies: [{ author: 'Designer', text: 'Revised on S101', at: 200 }] };
  const measurement = { id: 'length', page: 0, kind: 'Length', points: [[20, 20], [120, 20]], scale: { unit: 'ft', unitsPerPoint: .1 } };
  const data = { scales: { 0: measurement.scale }, review: [mark], reviewMeta: { [mark.id]: meta }, measurements: [measurement] };
  assert.equal(validateReviewMark(mark, 2), true);
  assert.equal(validateReviewMark({ ...mark, points: [[NaN, 0], [1, 1]] }, 2), false);
  assert.ok(reviewGeometry(mark).paths.length >= 3);
  const result = await exportDrawingPdf(bytes, data, [2, 1]);
  const exported = await PDFDocument.load(result);
  const annotations = exported.getPage(1).node.Annots();
  assert.equal(annotations.size(), 3);
  assert.equal(annotations.lookup(0).get(PDFName.of('Subtype')).toString(), '/FreeText');
  assert.ok(annotations.lookup(0).lookup(PDFName.of('AP')) instanceof PDFDict);
  assert.ok(annotations.lookup(2).lookup(PDFName.of('Measure')) instanceof PDFDict);
  const imported = await importDrawingPdf(result);
  assert.equal(imported.drawing.review[0].page, 1);
  assert.equal(imported.drawing.review[0].text, mark.text);
  assert.deepEqual(imported.drawing.reviewMeta[mark.id], meta);
  assert.equal(imported.drawing.measurements[0].page, 1);
  assert.deepEqual(imported.drawing.scales[1], measurement.scale);
  assert.equal((await PDFDocument.load(imported.bytes)).getPage(1).node.Annots().size(), 0, 'native appearances are removed before editable overlays are displayed');
  // External readers may move the annotation and change its note. Those edits win over the stored geometry.
  const annotation = annotations.lookup(0), rect = annotation.lookup(PDFName.of('Rect')).asArray().map(v => v.asNumber());
  annotation.set(PDFName.of('Contents'), PDFHexString.fromText('Changed in another reader'));
  annotation.set(PDFName.of('Rect'), exported.context.obj(rect.map((n, i) => n + (i % 2 ? 5 : 10))));
  annotation.set(PDFName.of('State'), PDFHexString.fromText('Completed'));
  exported.getPage(1).node.addAnnot(exported.context.register(exported.context.obj({ Type: 'Annot', Subtype: 'Text', Rect: [20, 20, 40, 40], IRT: annotations.get(0), RT: 'R', Contents: PDFHexString.fromText('External reviewer reply'), T: PDFHexString.fromText('External reviewer') })));
  const moved = await importDrawingPdf(await exported.save());
  assert.equal(moved.drawing.reviewMeta[mark.id].status, 'Resolved');
  assert.ok(moved.drawing.reviewMeta[mark.id].replies.some(r => r.text === 'External reviewer reply'));
  assert.equal(moved.drawing.review[0].text, 'Changed in another reader');
  assert.deepEqual(moved.drawing.review[0].points[0], [50, 455]);
  const again = await PDFDocument.load(await exportDrawingPdf(imported.bytes, imported.drawing));
  assert.equal(again.getPage(1).node.Annots().size(), 3, 'saving again does not duplicate marks');
  const flat = await PDFDocument.load(await exportDrawingPdf(bytes, data, null, true));
  assert.equal(flat.getPage(0).node.Annots().size(), 0);
  assert.ok(flat.getPage(0).node.Contents());
  assert.equal((await importDrawingPdf(await flat.save())).drawing, undefined);
  const malformed = await PDFDocument.load(result);
  malformed.getPage(1).node.Annots().lookup(0).set(PDFName.of('FolioReview'), PDFHexString.fromText('{broken'));
  const safe = await importDrawingPdf(await malformed.save());
  assert.equal((await PDFDocument.load(safe.bytes)).getPage(1).node.Annots().size(), 2, 'invalid records leave their visible annotations intact');
  const nativeDoc = await PDFDocument.load(bytes);
  const nativeRef = nativeDoc.context.register(nativeDoc.context.obj({ Type: 'Annot', Subtype: 'FreeText', Rect: [20, 20, 120, 50], Contents: PDFHexString.fromText('Existing note') }));
  nativeDoc.getPage(0).node.addAnnot(nativeRef);
  const nativeData = { scales: {}, measurements: [], reviewMeta: { 'existing-note': meta } };
  const nativeSaved = await exportDrawingPdf(await nativeDoc.save(), nativeData, null, false, undefined, [{ id: 'existing-note', page: 0, type: 'freetext', text: 'Existing note', data: { rect: [20, 20, 120, 50] } }]);
  const nativeImported = await importDrawingPdf(nativeSaved);
  assert.ok(Object.values(nativeImported.drawing.reviewMeta).some(m => m.subject === meta.subject && m.status === meta.status), 'review fields on existing Folio annotations survive exported copies');
  const formDoc = await PDFDocument.load(bytes);
  const field = formDoc.getForm().createTextField('test'); field.setText('Filled form'); field.addToPage(formDoc.getPage(0), { x: 10, y: 100, width: 120, height: 20 });
  formDoc.getForm().updateFieldAppearances();
  const finalForm = await PDFDocument.load(await exportDrawingPdf(await formDoc.save(), { scales: {}, measurements: [] }, null, true));
  assert.equal(finalForm.getForm().getFields().length, 0, 'flattened copies do not retain editable form fields');
  const unicode = { ...data, review: [{ ...mark, text: 'Διάσταση — размер' }] };
  const font = new Uint8Array(readFileSync('node_modules/pdfjs-dist/standard_fonts/LiberationSans-Regular.ttf'));
  const international = await exportDrawingPdf(bytes, unicode, undefined, false, font);
  assert.equal((await importDrawingPdf(international)).drawing.review[0].text, unicode.review[0].text);
  const rows = reviewRows(data, [], measurementLabel);
  assert.equal(rows.length, 2); assert.match(reviewCsv(rows), /Answered/);
  assert.match(reviewCsv([{ ...rows[0], text: '=HYPERLINK("bad")' }]), /'=HYPERLINK/);
  assert.equal((await PDFDocument.load(await reviewReport(rows, 'Review report'))).getPageCount(), 1);
  assert.deepEqual(snapPoint([9.8, 10.2], [[10, 10]], 1).point, [10, 10]);
  assert.deepEqual(snapPoint([9.8, 10.2], [], 1).point, [9.8, 10.2]);
  const angle = snapPoint([10, 2], [], 1, [0, 0], true).point;
  assert.equal(angle[1], 0);
  assert.deepEqual(alignRevision([[10, 20], [10, 40]], [[0, 0], [10, 0]]), [0, 2, -2, 0, 10, 20]);
  assert.throws(() => alignRevision([[0, 0], [1, 1]], [[0, 0], [0, 0]]));
  console.log('PASS review PDF round trips, external edits, flattening, Unicode, report, CSV, snapping and revision alignment');
} finally { await server.close(); }
