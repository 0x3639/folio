import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { PDFDocument } from 'pdf-lib';
export async function checkDrawingReview(app, page, output) {
  await page.getByRole('button', { name: 'Markup', exact: true }).click();
  await page.getByRole('complementary', { name: 'Drawing tools' }).getByRole('button', { name: 'Properties', exact: true }).click();
  await page.getByRole('button', { name: 'Collapse drawing toolbar', exact: true }).click();
  const panel = page.getByRole('complementary', { name: 'Drawing review' });
  await panel.waitFor();
  await panel.getByLabel('Review tool', { exact: true }).selectOption('Callout');
  await panel.getByLabel('Note or stamp text').fill('Verify beam clearance');
  await panel.getByLabel('Author', { exact: true }).fill('Plan reviewer');
  await panel.getByLabel('Discipline', { exact: true }).fill('Structural');
  await panel.getByLabel('Snap to vector endpoints').uncheck();
  const overlay = page.locator('.review-overlay.review-active').first();
  const box = await overlay.boundingBox();
  const x = box.x + 45, y = Math.max(box.y + 90, 160);
  await page.mouse.click(x, y + 90); await page.mouse.click(x + 160, y);
  await panel.getByLabel('Subject', { exact: true }).fill('Beam clearance');
  await panel.getByLabel('Review status', { exact: true }).selectOption('Answered');
  await panel.getByLabel('Reply', { exact: true }).fill('Please check the revised detail.');
  await panel.getByRole('button', { name: 'Add reply', exact: true }).click();
  await panel.getByText('Please check the revised detail.', { exact: true }).waitFor();
  await panel.getByLabel('Line style', { exact: true }).selectOption('dashed');
  await panel.getByLabel('Text size', { exact: true }).fill('14');
  await panel.locator('summary').filter({ hasText: 'Reusable tools' }).click();
  await panel.getByLabel('Tool name', { exact: true }).fill('Beam coordination');
  await panel.getByRole('button', { name: 'Save current tool', exact: true }).click();
  await panel.getByRole('option', { name: 'Beam coordination', exact: true }).waitFor({ state: 'attached' });
  await panel.getByRole('button', { name: 'Duplicate', exact: true }).click();
  assert.equal(await overlay.locator('g[data-review-id]').count(), 2);
  await panel.getByRole('button', { name: 'Undo', exact: true }).click();
  assert.equal(await overlay.locator('g[data-review-id]').count(), 1);
  await panel.getByRole('button', { name: 'Redo', exact: true }).click();
  assert.equal(await overlay.locator('g[data-review-id]').count(), 2);
  const checkboxes = panel.getByRole('checkbox', { name: 'Select Callout on sheet 1', exact: true });
  await checkboxes.first().check();
  await panel.getByRole('button', { name: 'Group', exact: true }).click();
  await panel.getByRole('button', { name: 'Lock', exact: true }).click();
  assert.equal(await panel.getByRole('button', { name: 'Delete', exact: true }).isDisabled(), true);
  await panel.getByRole('button', { name: 'Unlock', exact: true }).click();
  await panel.getByLabel('Move X (PDF points)').fill('10');
  await panel.getByRole('button', { name: 'Move', exact: true }).click();
  await panel.getByLabel('Filter status', { exact: true }).selectOption('Open');
  assert.equal(await panel.locator('.review-list li').count(), 0);
  await panel.getByLabel('Filter status', { exact: true }).selectOption('All');
  await panel.getByLabel('New layer', { exact: true }).fill('Structural review');
  await panel.getByRole('button', { name: 'Add layer', exact: true }).click();
  await panel.getByLabel('Selected layer', { exact: true }).selectOption({ label: 'Structural review' });
  await panel.getByLabel('Show layer Structural review', { exact: true }).uncheck();
  assert.equal(await overlay.locator('g[data-review-id]').count(), 0, 'hiding a layer removes its geometry and handles');
  await panel.getByRole('button', { name: 'Undo', exact: true }).click();
  assert.equal(await overlay.locator('g[data-review-id]').count(), 2, 'layer visibility is undoable');
  await panel.getByRole('button', { name: 'Redo', exact: true }).click();
  assert.equal(await overlay.locator('g[data-review-id]').count(), 0);
  await page.screenshot({ path: path.join(output, 'drawing-review.png') });
  const download = async (name, action) => {
    const file = path.join(output, name);
    await app.evaluate(({ session }, file) => {
      globalThis.reviewDownload = new Promise(resolve => session.defaultSession.once('will-download', (_event, item) => { item.setSavePath(file); item.once('done', (_e, status) => resolve(status)); }));
    }, file);
    await action();
    assert.equal(await app.evaluate(() => globalThis.reviewDownload), 'completed');
    return new Uint8Array(readFileSync(file));
  };
  const csv = await download('review.csv', () => panel.getByRole('button', { name: 'Export CSV', exact: true }).click());
  assert.match(new TextDecoder().decode(csv), /Beam clearance/);
  const report = await download('review-report.pdf', () => panel.getByRole('button', { name: 'Review report', exact: true }).click());
  assert.ok((await PDFDocument.load(report)).getPageCount() > 0);
  const saved = await download('review-editable.pdf', async () => {
    await page.getByRole('button', { name: 'More', exact: true }).click();
    await page.getByRole('menuitem', { name: /^Save a copy/ }).click();
  });
  const annotations = await page.evaluate(async bytes => {
    const task = pdfjsLib.getDocument({ data: Uint8Array.from(bytes) });
    try { const pdf = await task.promise; return (await (await pdf.getPage(1)).getAnnotations({ intent: 'any' })).map(a => ({ subtype: a.subtype, content: a.contentsObj?.str })); }
    finally { await task.destroy(); }
  }, Array.from(saved));
  assert.equal(annotations.filter(a => a.subtype === 'FreeText' && a.content === 'Verify beam clearance').length, 2);
  const pdfLayers = await page.evaluate(async bytes => {
    const task = pdfjsLib.getDocument({ data: Uint8Array.from(bytes) });
    try { const pdf = await task.promise, config = await pdf.getOptionalContentConfig(); return Array.from(config, ([, g]) => ({ name: g.name, visible: g.visible })); }
    finally { await task.destroy(); }
  }, Array.from(saved));
  assert.deepEqual(pdfLayers, [{ name: 'Structural review', visible: false }]);
  await panel.getByLabel('Show layer Structural review', { exact: true }).check();
  await panel.getByRole('button', { name: 'Compare revisions', exact: true }).click();
  const compare = page.getByRole('dialog', { name: 'Compare revisions', exact: true });
  await compare.getByLabel('Revised PDF', { exact: true }).setInputFiles({ name: 'revision.pdf', mimeType: 'application/pdf', buffer: Buffer.from(saved) });
  await compare.locator('img').nth(1).waitFor();
  await compare.getByLabel('Comparison view', { exact: true }).selectOption('Overlay');
  assert.equal(await compare.locator('.compare-pane').count(), 1);
  await compare.getByRole('button', { name: 'Align two points', exact: true }).click();
  const panes = compare.locator('.compare-pane');
  for (let i = 0; i < 2; i++) { const b = await panes.nth(i).boundingBox(); await page.mouse.click(b.x + 60, b.y + 70); await page.mouse.click(b.x + 150, b.y + 70); }
  await compare.getByLabel('Comparison view', { exact: true }).selectOption('Overlay');
  await page.screenshot({ path: path.join(output, 'revision-overlay.png') });
  await compare.getByRole('button', { name: 'Close comparison', exact: true }).click();
  await page.evaluate(() => { window.originalReviewConfirm = window.confirm; window.confirm = () => true; });
  const flat = await download('review-final.pdf', () => panel.getByRole('button', { name: 'Save flattened copy…', exact: true }).click());
  await page.evaluate(() => { window.confirm = window.originalReviewConfirm; });
  assert.equal((await PDFDocument.load(flat)).getPage(0).node.Annots()?.size() ?? 0, 0);
  await app.evaluate(({ BrowserWindow }, bytes) => BrowserWindow.getAllWindows()[0].webContents.send('folio:open-file', { name: 'review-editable.pdf', data: Buffer.from(bytes) }), Array.from(saved));
  await page.getByRole('button', { name: 'Markup', exact: true }).click();
  await page.getByRole('complementary', { name: 'Drawing tools' }).getByRole('button', { name: 'Properties', exact: true }).click();
  await page.getByRole('button', { name: 'Collapse drawing toolbar', exact: true }).click();
  await panel.getByRole('checkbox', { name: 'Select Callout on sheet 1', exact: true }).nth(1).waitFor();
  await panel.getByLabel('Show layer Structural review', { exact: true }).waitFor();
  assert.equal(await panel.getByLabel('Show layer Structural review', { exact: true }).isChecked(), false);
  assert.equal(await page.locator('.review-overlay g[data-review-id]').count(), 0);
  await panel.getByLabel('Show layer Structural review', { exact: true }).check();
  await panel.locator('.review-list button').first().click();
  await panel.getByText('Please check the revised detail.', { exact: true }).waitFor();
  await panel.getByLabel('Note or stamp text').fill('Checked after reopening');
  await page.locator('.review-overlay text').filter({ hasText: 'Checked after' }).first().waitFor();
  await panel.locator('summary').filter({ hasText: 'Reusable tools' }).click();
  await panel.getByLabel('Saved tool', { exact: true }).selectOption({ label: 'Beam coordination' });
  const reopenedBox = await page.locator('.review-overlay.review-active').first().boundingBox();
  await page.mouse.click(reopenedBox.x + 80, Math.max(reopenedBox.y + 300, 350));
  assert.equal(await page.locator('.review-overlay g[data-review-id]').count(), 3, 'saved geometry can be placed with one click after reopening');
  await panel.getByLabel('Review tool', { exact: true }).selectOption('Cloud callout');
  await panel.getByLabel('Note or stamp text').fill('Revise grid');
  const cloudBox = await page.locator('.review-overlay.review-active').first().boundingBox();
  const cy = Math.max(cloudBox.y + 260, 320);
  await page.mouse.click(cloudBox.x + 80, cy); await page.mouse.click(cloudBox.x + 160, cy + 50); await page.mouse.click(cloudBox.x + 200, cy - 60);
  assert.equal(await page.locator('.review-overlay g[data-review-id]').count(), 4, 'a cloud and callout form one editable mark');
  assert.ok(await page.locator('.review-overlay g[data-review-id]').last().locator('path').count() >= 3);
  const revised = await PDFDocument.create();
  const savedDoc = await PDFDocument.load(saved);
  for (const p of savedDoc.getPages()) revised.addPage([p.getWidth(), p.getHeight()]);
  await panel.getByRole('button', { name: 'Carry comments forward…', exact: true }).click();
  const transfer = page.getByRole('dialog', { name: 'Carry comments forward', exact: true });
  await transfer.getByLabel('Revised drawing', { exact: true }).setInputFiles({ name: 'drawing-revision.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await revised.save()) });
  await transfer.getByLabel('Destination for sheet 1', { exact: true }).selectOption('0');
  assert.equal(await transfer.getByRole('button', { name: 'Create reviewed copy', exact: true }).isDisabled(), true);
  await transfer.getByLabel('I checked the sheet matches and drawing alignment', { exact: true }).check();
  await transfer.getByRole('button', { name: 'Create reviewed copy', exact: true }).click();
  await transfer.getByText('4 marks carried forward; 0 duplicates skipped. Open the copy to verify placement, then save it.', { exact: true }).waitFor();
  await transfer.getByRole('button', { name: 'Open reviewed copy', exact: true }).click();
  await page.getByRole('tab', { name: 'drawing-revision-reviewed.pdf', selected: true, exact: true }).waitFor();
  await page.getByRole('button', { name: 'Markup', exact: true }).click();
  await page.getByRole('complementary', { name: 'Drawing tools' }).getByRole('button', { name: 'Properties', exact: true }).click();
  await page.getByRole('button', { name: 'Collapse drawing toolbar', exact: true }).click();
  await panel.locator('.review-list li').nth(3).waitFor();
  await panel.locator('.review-list button').first().click();
  await panel.getByText(/Carried from review-editable.pdf, sheet 1/).waitFor();
  assert.equal(await page.locator('.review-overlay g[data-review-id]').count(), 4);
  console.log('PASS standard PDF layers, undo/reopen visibility, explicit revision mapping and carried comments');
  const vector = await PDFDocument.create();
  vector.addPage([400, 400]).drawLine({ start: { x: 50, y: 100 }, end: { x: 150, y: 100 }, thickness: 1 });
  const vectorBytes = await vector.save();
  await app.evaluate(({ BrowserWindow }, bytes) => BrowserWindow.getAllWindows()[0].webContents.send('folio:open-file', { name: 'snap-fixture.pdf', data: Buffer.from(bytes) }), Array.from(vectorBytes));
  await page.getByRole('tab', { name: 'snap-fixture.pdf', selected: true, exact: true }).waitFor();
  await page.getByRole('button', { name: 'Measure', exact: true }).click();
  const measures = page.getByRole('region', { name: 'Drawing measurements' });
  await measures.waitFor();
  const surface = page.locator('.measurement-overlay.measuring').first();
  const vb = await surface.boundingBox();
  const clickPdf = (px, py) => page.mouse.click(vb.x + px / 400 * vb.width, vb.y + (400 - py) / 400 * vb.height);
  // Give the vector operator list time to arrive; the UI uses the cached list for subsequent clicks.
  await page.waitForTimeout(250);
  await clickPdf(51, 101); await clickPdf(149, 99);
  await page.waitForFunction(() => document.querySelector('[aria-label="Measurement tool"]').value === 'Length');
  await measures.getByLabel('Snap to drawing endpoints').uncheck();
  await clickPdf(50, 100); await clickPdf(150, 100);
  await measures.getByRole('button', { name: 'Length · p. 1 · 10.00 ft', exact: true }).waitFor();
  console.log('PASS real PDF vector endpoint snapping');
  console.log('PASS callouts, properties, groups, locks, statuses, replies, tools, reports, editable/flattened PDF exchange, comparison and reopening');
}
