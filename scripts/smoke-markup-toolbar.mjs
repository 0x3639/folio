import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { PDFDocument, rgb } from 'pdf-lib';

export async function checkMarkupToolbar(app, page, output) {
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 1000));
  const pdf = await PDFDocument.create(), sheet = pdf.addPage([1000, 700]);
  sheet.drawText('DRAWING REVIEW — TOOLBAR CHECK'.replace('—', '-'), { x: 60, y: 640, size: 22 });
  for (let i = 0; i < 5; i++) sheet.drawRectangle({ x: 280 + i * 100, y: 220, width: 80, height: 220, borderColor: rgb(.6, .65, .7), borderWidth: 1 });
  const open = async (name, bytes) => {
    await app.evaluate(({ BrowserWindow }, { name, bytes }) => BrowserWindow.getAllWindows()[0].webContents.send('folio:open-file', { name, data: Buffer.from(bytes) }), { name, bytes: Array.from(bytes) });
    await page.getByRole('tab', { name, selected: true, exact: true }).waitFor();
    await page.getByRole('button', { name: 'Markup', exact: true }).click();
    await page.getByRole('complementary', { name: 'Drawing tools' }).waitFor();
  };
  await open('toolbar-review.pdf', await pdf.save());
  const toolbar = page.getByRole('complementary', { name: 'Drawing tools' });
  const panel = page.getByRole('complementary', { name: 'Drawing review' });
  const overlay = page.locator('.review-overlay.review-active').first();
  const composer = page.getByRole('form', { name: 'Comment editor' });
  assert.equal(await panel.count(), 0, 'opening markup shows tools, not the advanced inspector');
  for (const name of ['Select', 'Comment', 'Arrow', 'Callout', 'Cloud callout', 'Text', 'Cloud', 'Rectangle', 'Oval', 'Line', 'Polygon', 'Stamp', 'Highlight', 'Freehand', 'Sign']) {
    assert.equal(await toolbar.getByRole('button', { name, exact: true }).isVisible(), true, `${name} is discoverable`);
  }
  const beforeMove = await toolbar.boundingBox();
  await toolbar.getByRole('button', { name: 'Move drawing toolbar', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal((await toolbar.boundingBox()).x, beforeMove.x + 20);
  await page.keyboard.press('Home');
  await toolbar.getByRole('button', { name: 'Collapse drawing toolbar', exact: true }).click();
  assert.equal(await toolbar.getByRole('button', { name: 'Comment', exact: true }).count(), 0);
  await toolbar.getByRole('button', { name: 'Expand drawing toolbar', exact: true }).click();
  const box = await overlay.boundingBox();
  const x = box.x + box.width * .48, y = box.y + box.height * .42;
  const marks = () => overlay.locator('g[data-review-id]:not([data-review-id=draft])');
  await toolbar.getByRole('button', { name: 'Comment', exact: true }).click();
  await page.mouse.click(x, y);
  await composer.getByLabel('Comment', { exact: true }).fill('Check beam clearance at this connection.');
  assert.equal(await composer.getByLabel('Comment', { exact: true }).evaluate(el => el === document.activeElement), true);
  await page.screenshot({ path: path.join(output, 'comment-composer.png') });
  await composer.getByRole('button', { name: 'Add comment', exact: true }).click();
  assert.equal(await marks().count(), 1);
  await toolbar.getByRole('button', { name: 'Comment', exact: true }).click();
  await page.mouse.click(x, y + 100);
  await composer.getByLabel('Comment', { exact: true }).fill('Do not save this');
  await page.keyboard.press('Escape');
  assert.equal(await composer.count(), 0);
  assert.equal(await marks().count(), 1, 'Escape does not leave an empty comment');
  await toolbar.getByRole('button', { name: 'Arrow', exact: true }).click();
  await toolbar.getByRole('button', { name: 'Style', exact: true }).click();
  assert.equal(await toolbar.getByRole('button', { name: 'Arrow', exact: true }).getAttribute('aria-pressed'), 'true', 'opening Style keeps the chosen tool');
  assert.equal(await panel.getByLabel('Author', { exact: true }).count(), 0, 'Style contains no reviewer fields');
  assert.equal(await panel.getByLabel('New layer', { exact: true }).count(), 0, 'Style contains no layer management');
  await panel.getByLabel('Stroke', { exact: true }).fill('#e5533d');
  await panel.getByRole('button', { name: 'Done', exact: true }).click();
  await page.mouse.move(x - 40, y + 160); await page.mouse.down();
  await page.mouse.move(x + 70, y + 80, { steps: 8 });
  assert.equal(await overlay.locator('[data-review-id=draft]').count(), 1, 'dragging previews the arrow');
  await page.mouse.up();
  assert.equal(await marks().count(), 2, 'dragging creates an arrow');
  await toolbar.getByRole('button', { name: 'Undo', exact: true }).click();
  assert.equal(await marks().count(), 1);
  await toolbar.getByRole('button', { name: 'Redo', exact: true }).click();
  assert.equal(await marks().count(), 2);
  await toolbar.getByRole('button', { name: 'Callout', exact: true }).click();
  await page.mouse.click(x - 20, y + 220); await page.mouse.click(x + 80, y + 180);
  await composer.getByLabel('Comment', { exact: true }).fill('Confirm revised dimension.');
  await composer.getByRole('button', { name: 'Add comment', exact: true }).click();
  assert.equal(await marks().count(), 3, 'callouts accept text after placement');
  await toolbar.getByRole('button', { name: 'Comments (3)', exact: true }).click();
  await panel.locator('.review-list button').filter({ hasText: 'Check beam clearance' }).click();
  await panel.getByLabel('Note or stamp text').fill('Clearance confirmed by reviewer.');
  await panel.getByLabel('Review status', { exact: true }).selectOption('Resolved');
  await panel.getByLabel('Reply', { exact: true }).fill('Reviewed on the latest sheet.');
  await panel.getByRole('button', { name: 'Add reply', exact: true }).click();
  await panel.getByRole('button', { name: 'Review details', exact: true }).click();
  await panel.getByLabel('Author', { exact: true }).fill('Coordination reviewer');
  await panel.getByLabel('Discipline', { exact: true }).fill('Structural');
  assert.equal(await panel.getByLabel('Stroke', { exact: true }).count(), 0, 'Review details contains no style controls');
  await page.screenshot({ path: path.join(output, 'review-details.png') });
  await panel.getByRole('button', { name: 'Style', exact: true }).click();
  assert.equal(await panel.getByLabel('Stroke', { exact: true }).inputValue(), '#333333', 'editing review details does not change the style');
  await panel.getByLabel('Stroke', { exact: true }).fill('#2f6fed');
  await panel.getByLabel('Fill', { exact: true }).fill('#eeeeff');
  await panel.getByLabel('Text size', { exact: true }).fill('16');
  await panel.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[aria-label="Text size"]')?.value === '12');
  assert.equal(await panel.getByLabel('Text size', { exact: true }).inputValue(), '12', 'Style updates after undo');
  await panel.getByRole('button', { name: 'Redo', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[aria-label="Text size"]')?.value === '16');
  assert.equal(await panel.getByLabel('Text size', { exact: true }).inputValue(), '16');
  await page.screenshot({ path: path.join(output, 'markup-style.png') });
  await panel.getByRole('button', { name: 'Review details', exact: true }).click();
  assert.equal(await panel.getByLabel('Author', { exact: true }).inputValue(), 'Coordination reviewer', 'editing style preserves review details');
  assert.equal(await panel.getByLabel('Review status', { exact: true }).inputValue(), 'Resolved');
  await panel.getByRole('button', { name: 'Done', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'markup-toolbar.png') });
  await toolbar.getByRole('button', { name: 'Measure', exact: true }).click();
  for (const mode of ['Calibrate', 'Length', 'Area', 'Perimeter', 'Count']) {
    await toolbar.getByRole('button', { name: mode, exact: true }).click();
    await page.waitForFunction(mode => document.querySelector('[aria-label="Measurement tool"]')?.value === mode, mode);
    assert.equal(await toolbar.isVisible(), true, 'toolbar remains open while measuring');
  }
  await toolbar.getByRole('button', { name: 'Markup', exact: true }).click();
  await toolbar.getByRole('button', { name: 'Freehand', exact: true }).click();
  assert.equal(await toolbar.isVisible(), true);
  await page.mouse.move(x - 60, y + 260); await page.mouse.down();
  await page.mouse.move(x + 30, y + 280, { steps: 10 }); await page.mouse.up();
  await toolbar.getByRole('button', { name: 'Highlight', exact: true }).click();
  await page.locator('.inkEditor').waitFor({ state: 'attached' });
  await toolbar.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.locator('.inkEditor').waitFor({ state: 'detached' });
  assert.equal(await page.locator('.review-overlay g[data-review-id]').count(), 3, 'freehand undo leaves review marks alone');
  await toolbar.getByRole('button', { name: 'Highlight', exact: true }).click();
  assert.equal(await toolbar.isVisible(), true);
  await toolbar.getByRole('button', { name: 'Select', exact: true }).click();
  await toolbar.getByRole('button', { name: 'Review', exact: true }).click();
  for (const name of ['Comments', 'Layers', 'Tool chest', 'Style', 'Review details', 'Arrange', 'Compare revisions', 'Carry comments', 'Export CSV', 'Review report', 'Flatten copy']) assert.equal(await toolbar.getByRole('button', { name, exact: true }).isVisible(), true);
  await toolbar.getByRole('button', { name: 'Layers', exact: true }).click();
  await panel.getByLabel('New layer', { exact: true }).waitFor();
  await toolbar.getByRole('button', { name: 'Tool chest', exact: true }).click();
  await panel.getByLabel('Saved tool', { exact: true }).waitFor();
  const file = path.join(output, 'toolbar-editable.pdf');
  await app.evaluate(({ session }, file) => {
    globalThis.toolbarDownload = new Promise(resolve => session.defaultSession.once('will-download', (_event, item) => { item.setSavePath(file); item.once('done', (_e, status) => resolve(status)); }));
  }, file);
  await toolbar.getByRole('button', { name: 'Save PDF copy', exact: true }).click();
  assert.equal(await app.evaluate(() => globalThis.toolbarDownload), 'completed');
  const bytes = new Uint8Array(readFileSync(file));
  const saved = await PDFDocument.load(bytes);
  assert.ok(saved.getPage(0).node.Annots().size() >= 3, 'saved marks are standard PDF annotations');
  await open('toolbar-reopened.pdf', bytes);
  await toolbar.getByRole('button', { name: 'Comments (3)', exact: true }).click();
  await panel.locator('.review-list button').filter({ hasText: 'Clearance confirmed' }).click();
  assert.equal(await panel.getByLabel('Review status', { exact: true }).inputValue(), 'Resolved');
  await panel.getByText('Reviewed on the latest sheet.', { exact: true }).waitFor();
  await panel.getByRole('button', { name: 'Review details', exact: true }).click();
  assert.equal(await panel.getByLabel('Author', { exact: true }).inputValue(), 'Coordination reviewer');
  await panel.getByRole('button', { name: 'Style', exact: true }).click();
  assert.equal(await panel.getByLabel('Stroke', { exact: true }).inputValue(), '#2f6fed');
  assert.equal(await panel.getByLabel('Fill', { exact: true }).inputValue(), '#eeeeff');
  await page.waitForFunction(() => document.querySelector('[aria-label="Text size"]')?.value === '16');
  assert.equal(await panel.getByLabel('Text size', { exact: true }).inputValue(), '16');
  console.log('PASS separate style, review details and layers; style undo/redo; independent PDF round trips');
  console.log('PASS discoverable toolbar, place-then-type comments, cancellation, drag preview, undo, callouts, replies, measurement/native switching and standard PDF save/reopen');
}
